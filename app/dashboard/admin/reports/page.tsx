export default function AdminReportsPage() {
  const [search, setSearch] = useState("");
  const [category, setCategory] = useState("All Categories");
  const [status, setStatus] = useState("All Statuses");
  const [dateRange, setDateRange] = useState("Last 30 days");
  const [showGenerateModal, setShowGenerateModal] = useState(false);
  const [reportName, setReportName] = useState("");
  const [reportCategory, setReportCategory] = useState("Patients");
  const [reportList, setReportList] = useState(reports);

  const filteredReports = useMemo(() => {
    return reportList.filter((report) => {
      const matchesSearch =
        report.name.toLowerCase().includes(search.toLowerCase()) ||
        report.id.toLowerCase().includes(search.toLowerCase());
      const matchesCategory =
        category === "All Categories" || report.category === category;
      const matchesStatus = status === "All Statuses" || report.status === status;
      return matchesSearch && matchesCategory && matchesStatus;
    });
  }, [reportList, search, category, status]);

  const generateReport = () => {
    if (!reportName.trim()) return;

    const newReport: Report = {
      id: `RPT-${Date.now().toString().slice(-4)}`,
      name: reportName.trim(),
      category: reportCategory,
      generatedBy: "Admin",
      date: new Date().toISOString().slice(0, 10),
      status: "Processing",
    };

    setReportList((current) => [newReport, ...current]);
    setReportName("");
    setShowGenerateModal(false);
  };

  const downloadReport = (report: Report) => {
    if (report.status !== "Ready") return;

    const csv = [
      "Report ID,Report Name,Category,Generated By,Date,Status",
      [
        report.id,
        `"${report.name.replace(/"/g, '""')}"`,
        report.category,
        report.generatedBy,
        report.date,
        report.status,
      ].join(","),
    ].join("\n");

    const blob = new Blob([csv], { type: "text/csv;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `${report.name.toLowerCase().replace(/\s+/g, "-")}.csv`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <DashboardShell>
      <div className="space-y-6">
        {/* Page heading */}
        <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
          <div>
            <h1 className="text-2xl font-semibold text-white">Reports</h1>
            <p className="mt-1 text-sm text-slate-400">
              Monitor hospital activity and generate operational reports.
            </p>
          </div>
          <button
            onClick={() => setShowGenerateModal(true)}
            className="inline-flex items-center justify-center gap-2 rounded-xl bg-cyan-500 px-4 py-2.5 text-sm font-medium text-slate-950 transition hover:bg-cyan-400"
          >
            <FileBarChart size={18} />
            Generate Report
          </button>
        </div>

        {/* Summary cards */}
        <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 xl:grid-cols-4">
          <SummaryCard
            title="Total Reports"
            value="128"
            change="+12 this month"
            icon={FileText}
            iconColor="bg-cyan-500/10 text-cyan-400"
          />
          <SummaryCard
            title="Patients"
            value="1,284"
            change="+8.4% from last month"
            icon={Users}
            iconColor="bg-blue-500/10 text-blue-400"
          />
          <SummaryCard
            title="Appointments"
            value="3,642"
            change="+5.2% from last month"
            icon={CalendarDays}
            iconColor="bg-violet-500/10 text-violet-400"
          />
          <SummaryCard
            title="Completion Rate"
            value="96.8%"
            change="Reports generated successfully"
            icon={CheckCircle2}
            iconColor="bg-emerald-500/10 text-emerald-400"
          />
        </div>

        {/* Analytics */}
        <div className="grid grid-cols-1 gap-6 xl:grid-cols-3">
          <section className="rounded-2xl border border-white/[0.07] bg-[#111c2e]/80 p-5 xl:col-span-2">
            <div className="mb-6 flex flex-wrap items-start justify-between gap-3">
              <div>
                <h2 className="font-semibold text-white">Patient Overview</h2>
                <p className="mt-1 text-sm text-slate-400">
                  Monthly patient registrations
                </p>
              </div>
              <select
                value={dateRange}
                onChange={(e) => setDateRange(e.target.value)}
                className="rounded-lg border border-white/10 bg-[#0b1424] px-3 py-2 text-sm text-slate-300 outline-none focus:border-cyan-500"
              >
                <option>Last 30 days</option>
                <option>Last 6 months</option>
                <option>This year</option>
              </select>
            </div>

            <div className="flex h-56 items-end gap-3 sm:gap-5">
              {monthlyPatients.map((item) => (
                <div
                  key={item.month}
                  className="flex h-full flex-1 flex-col items-center justify-end gap-2"
                >
                  <span className="text-xs text-slate-400">{item.value}</span>
                  <div className="flex w-full flex-1 items-end">
                    <div
                      className="w-full rounded-t-lg bg-gradient-to-t from-cyan-600 to-cyan-400 transition-all"
                      style={{ height: `${(item.value / 100) * 100}%` }}
                    />
                  </div>
                  <span className="text-xs text-slate-500">{item.month}</span>
                </div>
              ))}
            </div>
          </section>

          <section className="rounded-2xl border border-white/[0.07] bg-[#111c2e]/80 p-5">
            <div className="mb-6">
              <h2 className="font-semibold text-white">Department Activity</h2>
              <p className="mt-1 text-sm text-slate-400">
                Patient visits by department
              </p>
            </div>
            <div className="space-y-5">
              {departmentData.map((department) => (
                <div key={department.name}>
                  <div className="mb-2 flex items-center justify-between text-sm">
                    <span className="text-slate-300">{department.name}</span>
                    <span className="text-slate-400">{department.value}%</span>
                  </div>
                  <div className="h-2 overflow-hidden rounded-full bg-white/[0.06]">
                    <div
                      className={`h-full rounded-full ${department.color}`}
                      style={{ width: `${department.value}%` }}
                    />
                  </div>
                </div>
              ))}
            </div>
          </section>
        </div>

        {/* Report history */}
        <section className="overflow-hidden rounded-2xl border border-white/[0.07] bg-[#111c2e]/80">
          <div className="flex flex-col gap-4 border-b border-white/[0.07] p-5 lg:flex-row lg:items-center lg:justify-between">
            <div>
              <h2 className="font-semibold text-white">Report History</h2>
              <p className="mt-1 text-sm text-slate-400">
                View, filter, and download generated reports.
              </p>
            </div>
            <div className="flex flex-col gap-3 sm:flex-row">
              <div className="relative">
                <Search
                  size={16}
                  className="absolute left-3 top-1/2 -translate-y-1/2 text-slate-500"
                />
                <input
                  value={search}
                  onChange={(e) => setSearch(e.target.value)}
                  placeholder="Search reports..."
                  className="w-full rounded-lg border border-white/10 bg-[#0b1424] py-2 pl-9 pr-3 text-sm text-white outline-none placeholder:text-slate-500 focus:border-cyan-500 sm:w-56"
                />
              </div>
              <select
                value={category}
                onChange={(e) => setCategory(e.target.value)}
                className="rounded-lg border border-white/10 bg-[#0b1424] px-3 py-2 text-sm text-slate-300 outline-none focus:border-cyan-500"
              >
                <option>All Categories</option>
                <option>Patients</option>
                <option>Appointments</option>
                <option>Departments</option>
                <option>Doctors</option>
                <option>Finance</option>
              </select>
              <select
                value={status}
                onChange={(e) => setStatus(e.target.value)}
                className="rounded-lg border border-white/10 bg-[#0b1424] px-3 py-2 text-sm text-slate-300 outline-none focus:border-cyan-500"
              >
                <option>All Statuses</option>
                <option>Ready</option>
                <option>Processing</option>
                <option>Failed</option>
              </select>
            </div>
          </div>

          <div className="overflow-x-auto">
            <table className="w-full min-w-[760px] text-left text-sm">
              <thead className="bg-white/[0.02] text-xs uppercase tracking-wider text-slate-500">
                <tr>
                  <th className="px-5 py-4 font-medium">Report</th>
                  <th className="px-5 py-4 font-medium">Category</th>
                  <th className="px-5 py-4 font-medium">Generated By</th>
                  <th className="px-5 py-4 font-medium">Date</th>
                  <th className="px-5 py-4 font-medium">Status</th>
                  <th className="px-5 py-4 text-right font-medium">Actions</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-white/[0.05]">
                {filteredReports.map((report) => (
                  <tr key={report.id} className="transition hover:bg-white/[0.02]">
                    <td className="px-5 py-4">
                      <div className="font-medium text-white">{report.name}</div>
                      <div className="mt-1 text-xs text-slate-500">{report.id}</div>
                    </td>
                    <td className="px-5 py-4 text-slate-300">{report.category}</td>
                    <td className="px-5 py-4 text-slate-300">{report.generatedBy}</td>
                    <td className="px-5 py-4 text-slate-400">{report.date}</td>
                    <td className="px-5 py-4">
                      <span
                        className={`inline-flex rounded-full border px-2.5 py-1 text-xs font-medium ${statusStyles[report.status]}`}
                      >
                        {report.status}
                      </span>
                    </td>
                    <td className="px-5 py-4">
                      <div className="flex justify-end gap-2">
                        <button
                          onClick={() => downloadReport(report)}
                          disabled={report.status !== "Ready"}
                          title="Download CSV"
                          className="rounded-lg p-2 text-slate-400 transition hover:bg-cyan-500/10 hover:text-cyan-400 disabled:cursor-not-allowed disabled:opacity-30"
                        >
                          <ArrowDownToLine size={16} />
                        </button>
                        <button
                          title="More options"
                          className="rounded-lg p-2 text-slate-400 transition hover:bg-white/5 hover:text-white"
                        >
                          <MoreHorizontal size={16} />
                        </button>
                      </div>
                    </td>
                  </tr>
                ))}
                {filteredReports.length === 0 && (
                  <tr>
                    <td colSpan={6} className="px-5 py-12 text-center text-slate-500">
                      No reports match your filters.
                    </td>
                  </tr>
                )}
              </tbody>
            </table>
          </div>
          <div className="flex items-center justify-between border-t border-white/[0.07] px-5 py-4 text-xs text-slate-500">
            <span>Showing {filteredReports.length} of {reportList.length} reports</span>
            <span>Mock data</span>
          </div>
        </section>
      </div>

      {/* Generate report modal */}
      {showGenerateModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4 backdrop-blur-sm">
          <div className="w-full max-w-md rounded-2xl border border-white/10 bg-[#111c2e] p-6 shadow-2xl">
            <div className="mb-5 flex items-center justify-between">
              <div>
                <h2 className="text-lg font-semibold text-white">Generate Report</h2>
                <p className="mt-1 text-sm text-slate-400">
                  Create a new report using mock data.
                </p>
              </div>
              <button
                onClick={() => setShowGenerateModal(false)}
                className="rounded-lg p-2 text-slate-400 hover:bg-white/5 hover:text-white"
              >
                ✕
              </button>
            </div>

            <form
              onSubmit={(e) => {
                e.preventDefault();
                generateReport();
              }}
              className="space-y-4"
            >
              <div>
                <label className="mb-2 block text-sm text-slate-300">
                  Report Name
                </label>
                <input
                  value={reportName}
                  onChange={(e) => setReportName(e.target.value)}
                  required
                  placeholder="e.g. Weekly Patient Summary"
                  className="w-full rounded-lg border border-white/10 bg-[#0b1424] px-3 py-2.5 text-sm text-white outline-none placeholder:text-slate-500 focus:border-cyan-500"
                />
              </div>
              <div>
                <label className="mb-2 block text-sm text-slate-300">
                  Category
                </label>
                <select
                  value={reportCategory}
                  onChange={(e) => setReportCategory(e.target.value)}
                  className="w-full rounded-lg border border-white/10 bg-[#0b1424] px-3 py-2.5 text-sm text-slate-300 outline-none focus:border-cyan-500"
                >
                  <option>Patients</option>
                  <option>Appointments</option>
                  <option>Departments</option>
                  <option>Doctors</option>
                  <option>Finance</option>
                </select>
              </div>
              <div className="flex justify-end gap-3 pt-2">
                <button
                  type="button"
                  onClick={() => setShowGenerateModal(false)}
                  className="rounded-lg border border-white/10 px-4 py-2 text-sm text-slate-300 transition hover:bg-white/5"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  className="rounded-lg bg-cyan-500 px-4 py-2 text-sm font-medium text-slate-950 transition hover:bg-cyan-400"
                >
                  Generate
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </DashboardShell>
  );
}
